//! Implements docs/04-document-model.md §3.1–§3.8: the non-mesh entity types
//! (groups, component instances and definitions, guides, dimensions, text,
//! images, section planes). Edges and faces live in the container's
//! `HalfEdgeMesh` (docs/03).

use glam::{DAffine3, DVec2, DVec3};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::document::attributes::AttributeDictionaries;
use crate::document::hierarchy::Entities;
use crate::document::materials::ImageRef;
use crate::document::selection::EntityPath;
use crate::ids::{DefinitionId, MaterialId};
use crate::math::Plane;
use crate::units::{Length, LengthUnit};

/// A group: a single-instance anonymous component (docs/04 §3.1). Its
/// definition is private and copy-on-edit.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Group {
    /// The private definition (exactly one instance until copied).
    pub definition: DefinitionId,
    /// Placement in the parent container.
    pub transform: DAffine3,
    /// User-visible name (may be empty).
    pub name: String,
}

/// A placement of a component definition (docs/04 §3.2).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ComponentInstance {
    /// Shared definition.
    pub definition: DefinitionId,
    /// Placement in the parent container.
    pub transform: DAffine3,
    /// Optional instance name.
    pub name: Option<String>,
    /// Applied to faces with the *default* material inside.
    pub material_override: Option<MaterialId>,
    /// Face this instance is glued to.
    pub glued_to: Option<EntityPath>,
    /// Per-instance attributes.
    pub dynamic_attrs: AttributeDictionaries,
}

/// Gluing behavior (docs/04 §3.3 `GlueTo`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum GlueTo {
    /// Never glues.
    #[default]
    None,
    /// Horizontal faces only.
    Horizontal,
    /// Vertical faces only.
    Vertical,
    /// Sloped faces only.
    Sloped,
    /// Any face.
    Any,
}

/// Snapping behavior on placement (docs/04 §3.3 `SnapTo`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum SnapTo {
    /// No snapping constraint.
    #[default]
    None,
    /// Horizontal faces.
    Horizontal,
    /// Vertical faces.
    Vertical,
    /// Sloped faces.
    Sloped,
    /// Any face.
    Any,
}

/// Component behavior flags (docs/04 §3.3 `ComponentBehavior`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ComponentBehavior {
    /// Gluing.
    pub glue_to: GlueTo,
    /// Hides the face region it is glued on (windows/doors).
    pub cuts_opening: bool,
    /// 2D billboard behavior.
    pub always_face_camera: bool,
    /// Billboard shadows face the sun.
    pub shadows_face_sun: bool,
    /// Snapping.
    pub snap_to: SnapTo,
    /// Insertion point relative to the definition origin.
    pub insertion_point: DVec3,
    /// Definition axes (can be relocated).
    pub axes: DAffine3,
}

impl Default for ComponentBehavior {
    fn default() -> Self {
        ComponentBehavior {
            glue_to: GlueTo::None,
            cuts_opening: false,
            always_face_camera: false,
            shadows_face_sun: false,
            snap_to: SnapTo::None,
            insertion_point: DVec3::ZERO,
            axes: DAffine3::IDENTITY,
        }
    }
}

/// A component definition (docs/04 §3.3).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ComponentDefinition {
    /// Cross-file identity (v4).
    pub uuid: Uuid,
    /// Name (unique among non-internal definitions).
    pub name: String,
    /// Description.
    pub description: String,
    /// Contents.
    pub entities: Entities,
    /// Behavior.
    pub behavior: ComponentBehavior,
    /// `true` for the private definition of a group.
    pub is_internal_group: bool,
    /// Preview image.
    pub thumbnail: Option<ImageRef>,
    /// Attributes.
    pub attrs: AttributeDictionaries,
    /// Cached number of instances (recomputed by `validate`/`repair`).
    pub usage_count: u32,
}

impl ComponentDefinition {
    /// An empty definition. The UUID is generated by the caller (commands take
    /// it as a parameter or the engine supplies it) so this constructor stays
    /// deterministic.
    pub fn new(uuid: Uuid, name: impl Into<String>) -> Self {
        ComponentDefinition {
            uuid,
            name: name.into(),
            description: String::new(),
            entities: Entities::new(),
            behavior: ComponentBehavior::default(),
            is_internal_group: false,
            thumbnail: None,
            attrs: AttributeDictionaries::default(),
            usage_count: 0,
        }
    }
}

/// A construction guide (docs/04 §3.4).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum Guide {
    /// Infinite or finite guide line.
    Line {
        /// A point on the line.
        origin: DVec3,
        /// Unit direction.
        dir: DVec3,
        /// Parameter range for a finite guide, `None` = infinite.
        finite: Option<(f64, f64)>,
    },
    /// Guide point.
    Point {
        /// Position.
        pos: DVec3,
    },
}

/// What an anchor points at (docs/04 §3.5 `Anchor::kind`, Decisions):
/// an end or the middle of the edge `Anchor::path` names (by pid, so the
/// anchor survives saving and follows the edge when it moves), or a fixed
/// point.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize, JsonSchema)]
pub enum AnchorKind {
    /// The edge's first vertex.
    Start,
    /// The edge's second vertex.
    End,
    /// The edge's midpoint.
    Mid,
    /// A fixed point in the coordinates of the container `path.instances`
    /// reaches (`path.target` is unused).
    Point(#[schemars(with = "[f64; 3]")] DVec3),
}

/// A re-resolvable reference from a dimension or text (docs/04 §3.5).
/// `path` is relative to the container holding the dimension or text: its
/// steps start in that container.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct Anchor {
    /// Occurrence the anchor lives in, and the edge it follows.
    pub path: EntityPath,
    /// Target within that occurrence.
    pub kind: AnchorKind,
}

/// Arrow head style for dimensions.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "kebab-case")]
pub enum ArrowStyle {
    /// Architectural slash.
    #[default]
    Slash,
    /// Closed filled arrow.
    Closed,
    /// Open arrow.
    Open,
    /// Dot.
    Dot,
    /// None.
    None,
}

/// Dimension appearance (docs/04 §3.5 `DimStyle`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DimStyle {
    /// Text height in mm (model space) — screen-sized text is a frontend option.
    pub text_height: Length,
    /// Arrow heads.
    pub arrow: ArrowStyle,
    /// Unit override (`None` = document display units).
    pub units: Option<LengthUnit>,
    /// Precision override.
    pub precision: Option<u8>,
}

impl Default for DimStyle {
    fn default() -> Self {
        DimStyle {
            text_height: Length::mm(100.0),
            arrow: ArrowStyle::Slash,
            units: None,
            precision: None,
        }
    }
}

/// Radius or diameter (docs/04 §3.5 `Radial::kind`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum RadialKind {
    /// Radius.
    Radius,
    /// Diameter.
    Diameter,
}

/// A dimension (docs/04 §3.5); re-measures from its anchors on read.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum Dimension {
    /// Linear/aligned dimension.
    Linear {
        /// First anchor.
        start: Anchor,
        /// Second anchor.
        end: Anchor,
        /// Leader direction and length.
        offset: DVec3,
        /// Measured along this unit direction (a linear dimension); `None`
        /// measures the true distance (aligned).
        #[serde(default)]
        direction: Option<DVec3>,
        /// Style.
        style: DimStyle,
        /// Replaces the measured text (`<>` stands for the measurement).
        text_override: Option<String>,
    },
    /// Radius/diameter of a curve.
    Radial {
        /// Anchor on a member edge of the curve.
        curve: Anchor,
        /// Radius or diameter.
        kind: RadialKind,
        /// Leader vector.
        leader: DVec3,
        /// Style.
        style: DimStyle,
        /// Replaces the measured text.
        text_override: Option<String>,
    },
}

/// Screen-space text with an optional leader (docs/04 §3.6 `ScreenText`).
/// 3D text is not an entity: it generates faces in a group.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Text {
    /// Leader target.
    pub anchor: Option<Anchor>,
    /// Content.
    pub text: String,
    /// Offset from the anchor in screen pixels.
    pub screen_offset: DVec2,
}

/// A textured rectangle (docs/04 §3.7); can be exploded into a face.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ImageEntity {
    /// Width in mm.
    pub width: Length,
    /// Height in mm.
    pub height: Length,
    /// Placement (the rectangle lies in its local XY plane).
    pub transform: DAffine3,
    /// Material carrying the texture.
    pub material: MaterialId,
}

/// A section plane (docs/04 §3.8); cuts only its container's contents.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SectionPlane {
    /// Cutting plane; geometry on the `+normal` side is hidden.
    pub plane: Plane,
    /// Name.
    pub name: String,
    /// Short symbol shown on the widget.
    pub symbol: String,
    /// At most one active per container level.
    pub active: bool,
    /// Draw a cap fill on solids.
    pub fill_cap: bool,
    /// Also cut hidden geometry.
    pub cuts_hidden: bool,
}
